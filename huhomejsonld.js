const target = document.querySelector('#CategoryProducts');

if (target) {
  // 1. Check if Slick already initialized (e.g. fast cached execution)
  if (target.classList.contains('slick-initialized')) {
    huGenerateCleanJSONLD();
  } else {
    // 2. Otherwise, watch for the class mutation when Slick boots up
    const observer = new MutationObserver((mutations, obs) => {
      if (target.classList.contains('slick-initialized')) {
        huGenerateCleanJSONLD();
        obs.disconnect(); // Stop watching immediately
      }
    });
    observer.observe(target, { attributes: true, attributeFilter: ['class'] });
  }
}

function huGenerateCleanJSONLD() {
  // Target the raw cards, ignoring the duplicate nodes generated by Slick Slider
  const uniqueOffers = document.querySelectorAll('#CategoryProducts .HotDeal:not(.slick-cloned)');
  if (!uniqueOffers.length) return;

  const itemListElements = [];

  uniqueOffers.forEach((offerEl, index) => {
    // Safely extract the item details from the existing markup structures
    const name = offerEl.querySelector('.ProductName')?.innerText || 'Product';
    const image = offerEl.querySelector('.ProductHotDealImage')?.src || '';
    const price = offerEl.querySelector('[itemprop="price"]')?.getAttribute('content') || '';
    const currency = offerEl.querySelector('[itemprop="priceCurrency"]')?.getAttribute('content') || 'EUR';
    
    // Extract deep product link path
    const linkEl = offerEl.querySelector('.ProductName');

     const url = linkEl?.getAttribute('href') 
                ? new URL(linkEl.getAttribute('href'), window.location.href).href 
                : null;

    // --- NEW: Extract and clean old price if it exists ---
    const oldPriceEl = offerEl.querySelector('.hotdeal-old-price.LineThrough');
    let oldPrice = null;
    if (oldPriceEl) {
      const oldPriceRaw = oldPriceEl.innerText || '';
      // Clean string: remove spaces/currency symbols and swap comma to dot for schema compliance
      oldPrice = oldPriceRaw
                .replace(/[^\d,.-]/g, '')
                .replace(/\./g, '')
                .replace(',', '.');
    }

    // Base offer object with current active sale price
    const offersObj = {
      "@type": "Offer",
      "price": price,
      "priceCurrency": currency,
    };

    // Attach original price specification if found
    if (oldPrice && !isNaN(parseFloat(oldPrice))) {
      offersObj.priceSpecification = {
        "@type": "UnitPriceSpecification",
        "priceType": "https://schema.org/StrikethroughPrice",
        "price": oldPrice,
        "priceCurrency": currency
      };
    }
    // ----------------------------------------------------

    // Push into the structural array ordered by its visual position
    itemListElements.push({
      "@type": "ListItem",
      "position": index + 1,
      "item": {
        "@type": "Product",
        "name": name,
        "image": image,
        "url": url,
        "offers": offersObj
      }
    });
  });

  // Build the master structural parent container
  const masterSchema = {
    "@context": "https://schema.org",
    "@type": "ItemList",
    "name": "Hot Deals",
    "url": window.location.href,
    "numberOfItems": itemListElements.length,
    "itemListElement": itemListElements
  };

  // Inject the structured JSON-LD block directly into document head
  const script = document.createElement('script');
  script.type = 'application/ld+json';
  script.text = JSON.stringify(masterSchema);
  document.head.appendChild(script);
}
